"""The league table of the minimal circuit search (minimal/LEAGUE.md): every tuned design in minimal/results,
re-validated under the current rules (held-out lives, with the simulator's noise and mismatch, the slew limit).

Entry: doing the job (minimal/spec.py, JOB), within the slew limit. Ranking: parts and
power, 50:50: the geometric mean of best / own for each, so that twice the parts costs as much as twice the power.
Pareto: no other design that does the job has both fewer (or as few) parts and less (or as little) power. The near
misses (failing the job) are listed apart: a small, frugal near miss is worth knowing about.

    python -m minimal.league
"""

from __future__ import annotations

import glob
import hashlib
import json
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from minimal.spec import JOB, SLEW, parts, slew  # noqa: E402

HERE = os.path.dirname(__file__)
CACHE = os.path.join(HERE, "results", "league_cache.json")
SKIP = ("_round1", "_unlimited", "_start", "_feasible", "_fixednoise", "league_cache", "evolve", "C_tuned")  # (copies)
# (results tuned under the old noise, before 2026-10-20's model, are re-validated under the new like any other)


def validated(spec) -> dict:
    """The held-out summary, cached by the spec and the simulating and scoring code."""
    from minimal.search import validate
    import inspect
    import minimal.fastlife
    import minimal.spec
    import mixed_feedback
    code = inspect.getsource(minimal.spec) + inspect.getsource(minimal.fastlife) + inspect.getsource(mixed_feedback)
    key = hashlib.sha1((json.dumps(spec, sort_keys=True) + code).encode()).hexdigest()
    cache = json.load(open(CACHE)) if os.path.exists(CACHE) else {}
    if key not in cache:
        cache[key] = validate(spec)
        json.dump(cache, open(CACHE, "w"))
    return cache[key]


def rows():
    from minimal.designs import DESIGNS
    out = []
    for path in sorted(glob.glob(os.path.join(HERE, "results", "*.json"))):
        name = os.path.basename(path)[:-5]
        if any(s in name for s in SKIP):
            continue
        r = json.load(open(path))
        if "spec" in r:                                 # a circuit the open search found (minimal/evolve.py)
            spec = r["spec"]
        elif r.get("design") in DESIGNS:
            spec = DESIGNS[r["design"]][0](r["params"])
        else:
            continue
        from minimal.spec import violations
        bad = violations(spec)
        if bad:                                         # refused by the rules: not lived, listed apart
            out.append({"name": name, "parts": parts(spec)["total"], "illegal": "; ".join(bad)})
            continue
        v = validated(spec)
        pt = parts(spec)
        sl = slew(spec)
        fails = []
        if v["food"] < JOB[0]:
            fails.append(f"food {v['food']:.2f}")
        if v["last"] < JOB[1]:
            fails.append(f"food:poison {v['last']:.2f}")
        if sl > SLEW:
            fails.append(f"slew {sl:.0f}")
        out.append({"name": name, "parts": pt["total"], "blocks": pt["nodes"] + pt["elements"],
                    "power": v["power"], "v": v, "job": not fails, "fails": fails})
    return out


def table() -> str:
    rs = rows()
    illegal = [r for r in rs if "illegal" in r]
    rs = [r for r in rs if "illegal" not in r]
    good = [r for r in rs if r["job"]]
    bp = min((r["parts"] for r in good), default=1)
    bw = min((r["power"] for r in good), default=1.0)
    for r in rs:
        r["value"] = math.sqrt((bp / r["parts"]) * (bw / max(r["power"], 1e-9)))
        r["pareto"] = r["job"] and not any(o is not r and o["parts"] <= r["parts"] and o["power"] <= r["power"]
                                           and (o["parts"], o["power"]) != (r["parts"], r["power"]) for o in good)
    def line(k, r):
        v = r["v"]
        return (f"| {k} | {r['name']}{' (Pareto)' if r['pareto'] else ''} | {r['parts']} | {r['blocks']} |"
                f" {r['power']:.1f} | {r['value']:.2f} | {v['net']:+.2f} | {v['food']:.2f} | {v['last']:.2f} |"
                + (f" {', '.join(r['fails'])} |" if not r["job"] else ""))
    head = "| rank | design | parts | blocks | power | value | score | food | food:poison, last third |"
    out = ["# League table: the minimal circuit search", "",
           "Generated by `python -m minimal.league` (minimal/NOTEBOOK.md). Every design re-validated under the current",
           "rules: 64 held-out seeds x 2, with the simulator's noise and mismatch (mixed_feedback.py), within the slew",
           f"limit ({SLEW:g} V per circuit tick). **Job**: food at least {JOB[0]:g} per 1,000 ticks, food:poison at least",
           f"{JOB[1]:g} in the last third. **Parts**: capacitors, resistors, diodes, transistors. **Blocks**: level-0",
           "nodes and elements. **Power**: what the devices dissipate, each its current times the voltage across it",
           "(mixed_feedback._step).",
           "**Value**: parts and power 50:50, the geometric mean of (best / own) for each over the designs that do",
           "the job. **Pareto**: no design that does the job beats it on both. Score and food:poison as in the notebook.",
           "", "## Doing the job", "", head, "|---|---|---|---|---|---|---|---|---|"]
    for k, r in enumerate(sorted(good, key=lambda r: -r["value"])):
        out.append(line(k + 1, r))
    out += ["", "## Near misses (not doing the job)", "", head + " fails |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted((r for r in rs if not r["job"]), key=lambda r: -r["value"]):
        out.append(line("", r))
    out += ["", "## Refused by the rules (tuned before a rule existed)", "", "| design | parts | why |", "|---|---|---|"]
    out += [f"| {r['name']} | {r['parts']} | {r['illegal']} |" for r in sorted(illegal, key=lambda r: r["parts"])]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    t = table()
    open(os.path.join(HERE, "LEAGUE.md"), "w").write(t)
    print(t)
